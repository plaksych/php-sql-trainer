function renderCheatsheets() {
    const grid = document.getElementById('cheatsheet-grid');
    grid.innerHTML = '';

    const query = state.cheatsheets.searchQuery;

    CHEATSHEETS_DATA.forEach(section => {
        // Filter items
        const filteredItems = section.items.filter(item => 
            item.cmd.toLowerCase().includes(query) || 
            item.desc.toLowerCase().includes(query)
        );

        if (filteredItems.length === 0 && !section.title.toLowerCase().includes(query)) {
            return; // Skip this category if nothing matches
        }

        const card = document.createElement('div');
        card.className = 'sheet-card';
        
        let itemsHTML = '';
        const itemsToRender = filteredItems.length > 0 ? filteredItems : section.items;

        itemsToRender.forEach(item => {
            itemsHTML += `
                <div class="sheet-item">
                    <div class="sheet-item-header">
                        <span class="sheet-command">${escapeHTML(item.cmd)}</span>
                        <button class="card-action-btn" style="padding: 0.15rem 0.4rem; font-size: 0.75rem;" onclick="copyToClipboard('${escapeHTML(item.cmd.replace(/'/g, "\\'"))}')">
                            <i class="far fa-copy"></i>
                        </button>
                    </div>
                    <span class="sheet-desc">${item.desc}</span>
                </div>
            `;
        });

        card.innerHTML = `
            <h3 class="sheet-title">
                <i class="fas ${section.icon} text-purple"></i> ${section.title}
            </h3>
            <div class="sheet-list">
                ${itemsHTML}
            </div>
        `;
        grid.appendChild(card);
    });

    if (grid.children.length === 0) {
        grid.innerHTML = `
            <div style="grid-column: 1/-1; text-align: center; color: var(--text-secondary); padding: 3rem 0;">
                <i class="fas fa-search" style="font-size: 2rem; margin-bottom: 1rem; display: block;"></i>
                Ничего не найдено по вашему запросу
            </div>
        `;
    }
}

// Utility Helper Functions
function escapeHTML(str) {
    return str.replace(/[&<>'"]/g, 
        tag => ({
            '&': '&amp;',
            '<': '&lt;',
            '>': '&gt;',
            "'": '&#39;',
            '"': '&quot;'
        }[tag] || tag)
    );
}

function showAlertPopup(msg) {
    const existing = document.querySelector('.alert-popup');
    if (existing) existing.remove();

    const popup = document.createElement('div');
    popup.className = 'alert-popup';
    popup.innerHTML = `
        <i class="fas fa-check-circle" style="color: var(--success); font-size: 1.25rem;"></i>
        <span>${msg}</span>
    `;
    document.body.appendChild(popup);

    setTimeout(() => {
        popup.style.opacity = '0';
        popup.style.transform = 'translateY(20px) scale(0.95)';
        popup.style.transition = 'var(--transition-smooth)';
        setTimeout(() => popup.remove(), 300);
    }, 3000);
}

function copyToClipboard(text) {
    navigator.clipboard.writeText(text).then(() => {
        showAlertPopup("Команда скопирована в буфер обмена!");
    }).catch(err => {
        console.error('Ошибка копирования: ', err);
    });
}
