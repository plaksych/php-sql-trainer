// Sandbox execution env for PHP translated code
function runPracticeCode() {
    const problem = PRACTICE_PROBLEMS.find(p => p.id === state.practice.activeProblemId);
    const userCode = state.practice.editorValue;
    
    // Save to local storage
    localStorage.setItem(`practice_code_${problem.id}`, userCode);

    // Transpile PHP code to JavaScript
    let transpiledJS;
    try {
        transpiledJS = transpilePHP(userCode);
    } catch (e) {
        showCompilationError("Ошибка транслятора кода: " + e.message);
        return;
    }

    // Prepare sandbox helpers
    const helpersStr = `
        const empty = (x) => {
            if (!x) return true;
            if (Array.isArray(x) && x.length === 0) return true;
            if (typeof x === 'object') return Object.keys(x).length === 0;
            return false;
        };
        const count = (x) => {
            if (!x) return 0;
            if (Array.isArray(x) || typeof x === 'string') return x.length;
            if (typeof x === 'object') return Object.keys(x).length;
            return 0;
        };
        const in_array = (needle, haystack) => {
            if (!Array.isArray(haystack)) return false;
            return haystack.includes(needle);
        };
        const array_merge = (...arrs) => [].concat(...arrs);
        const array_keys = (obj) => Object.keys(obj);
        const array_values = (obj) => Object.values(obj);
        const explode = (delimiter, string) => string.split(delimiter);
        const implode = (glue, pieces) => pieces.join(glue);
        const round = (val, precision = 0) => Number(Math.round(val + 'e' + precision) + 'e-' + precision);
        const array_filter = (arr, cb) => arr.filter(cb);
        const array_map = (cb, arr) => arr.map(cb);
    `;

    const resultsContainer = document.getElementById('test-results-list');
    resultsContainer.innerHTML = '';

    let allTestsPassed = true;

    problem.tests.forEach((testCase, idx) => {
        let testPassed = false;
        let actualOutput = null;
        let errorMessage = null;

        try {
            // We construct an execution runner
            let execStr = "";
            
            if (problem.id === "p_5") {
                // OOP Specific Test: instantiate class Car and call getInfo()
                const brand = testCase.input[0];
                const model = testCase.input[1];
                
                execStr = `
                    ${helpersStr}
                    ${transpiledJS}
                    
                    if (typeof Car !== 'function') {
                        throw new Error("Класс 'Car' не найден!");
                    }
                    const obj = new Car("${brand}", "${model}");
                    obj.getInfo();
                `;
            } else {
                // Function Specific Test
                const functionName = problem.id === "p_1" ? "filterEven" : 
                                     problem.id === "p_2" ? "getInitials" :
                                     problem.id === "p_3" ? "calculateAverage" : 
                                     "getSafeValue";

                const serializedArgs = testCase.input.map(arg => JSON.stringify(arg)).join(', ');
                
                execStr = `
                    ${helpersStr}
                    ${transpiledJS}
                    
                    if (typeof ${functionName} !== 'function') {
                        throw new Error("Функция '${functionName}' не объявлена!");
                    }
                    ${functionName}(${serializedArgs});
                `;
            }

            // Execute in eval
            actualOutput = eval(execStr);

            // Compare result
            if (JSON.stringify(actualOutput) === JSON.stringify(testCase.expected)) {
                testPassed = true;
            } else {
                testPassed = false;
                allTestsPassed = false;
            }
        } catch (e) {
            errorMessage = e.message;
            testPassed = false;
            allTestsPassed = false;
        }

        // Render test result
        const testDiv = document.createElement('div');
        testDiv.className = `test-case-item ${testPassed ? 'pass' : 'fail'}`;
        
        let labelInputText = "";
        if (problem.id === "p_5") {
            labelInputText = `new Car("${testCase.input[0]}", "${testCase.input[1]}")->getInfo()`;
        } else {
            labelInputText = `Вход: ${JSON.stringify(testCase.input)}`;
        }

        testDiv.innerHTML = `
            <div>
                <strong>Тест ${idx + 1}:</strong> ${escapeHTML(labelInputText)}<br>
                <span style="font-size: 0.8rem; color: var(--text-secondary);">
                    Ожидалось: <code>${escapeHTML(JSON.stringify(testCase.expected))}</code> 
                    ${testPassed ? '' : ` | Получено: <code>${errorMessage ? 'Ошибка: ' + errorMessage : escapeHTML(JSON.stringify(actualOutput))}</code>`}
                </span>
            </div>
            <span class="test-status-pill ${testPassed ? 'pass' : 'fail'}">${testPassed ? 'Успешно' : 'Ошибка'}</span>
        `;
        resultsContainer.appendChild(testDiv);
    });

    if (allTestsPassed) {
        state.practice.solvedProblems[problem.id] = true;
        localStorage.setItem('solved_problems', JSON.stringify(state.practice.solvedProblems));
        
        // Show success alert
        showAlertPopup("🎉 Задача решена успешно! Все тесты пройдены.");
        
        // Update sidebar
        renderProblemsSidebar();
    }
}

