function renderQuestion() {
    const topic = state.quiz.activeTopic;
    const question = QUIZ_DATA[topic].questions[state.quiz.currentQuestionIndex];
    const totalQuestions = QUIZ_DATA[topic].questions.length;

    // Reset UI elements
    state.quiz.isAnswered = false;
    state.quiz.selectedOption = null;
    document.getElementById('quiz-next-btn').innerText = (state.quiz.currentQuestionIndex === totalQuestions - 1) ? "Завершить тест" : "Следующий вопрос";
    document.getElementById('quiz-next-btn').disabled = true;
    
    // Hide explanation
    const expBox = document.getElementById('quiz-explanation');
    expBox.style.display = 'none';

    // Update progress bar
    const progressPercent = (state.quiz.currentQuestionIndex / totalQuestions) * 100;
    document.getElementById('quiz-progress-fill').style.width = `${progressPercent}%`;
    document.getElementById('quiz-counter-text').innerText = `Вопрос ${state.quiz.currentQuestionIndex + 1} из ${totalQuestions}`;

    // Set question text
    document.getElementById('quiz-question-text').innerText = question.text;

    // Code block if exists
    const codeContainer = document.getElementById('quiz-code-container');
    if (question.code) {
        codeContainer.innerHTML = `<pre class="code-block"><code>${escapeHTML(question.code)}</code></pre>`;
        codeContainer.style.display = 'block';
    } else {
        codeContainer.style.display = 'none';
    }

    // Set options
    const optionsContainer = document.getElementById('quiz-options-container');
    optionsContainer.innerHTML = '';

    question.options.forEach((option, idx) => {
        const optionBtn = document.createElement('button');
        optionBtn.className = 'option-btn';
        optionBtn.innerHTML = `
            <span class="option-index">${String.fromCharCode(65 + idx)}</span>
            <span class="option-text">${escapeHTML(option)}</span>
        `;
        optionBtn.addEventListener('click', () => selectOption(idx));
        optionsContainer.appendChild(optionBtn);
    });

    document.getElementById('quiz-active-area').style.display = 'block';
    document.getElementById('quiz-score-screen').style.display = 'none';
}

function selectOption(optionIndex) {
    if (state.quiz.isAnswered) return;

    state.quiz.selectedOption = optionIndex;
    state.quiz.isAnswered = true;

    const topic = state.quiz.activeTopic;
    const question = QUIZ_DATA[topic].questions[state.quiz.currentQuestionIndex];
    const optionButtons = document.querySelectorAll('#quiz-options-container .option-btn');

    const isCorrect = (optionIndex === question.correct);
    if (isCorrect) {
        state.quiz.score++;
        optionButtons[optionIndex].classList.add('correct');
        state.quiz.answersHistory.push(true);
    } else {
        optionButtons[optionIndex].classList.add('incorrect');
        optionButtons[question.correct].classList.add('correct');
        state.quiz.answersHistory.push(false);
    }

    // Disable all options
    optionButtons.forEach(btn => btn.disabled = true);

    // Show Explanation
    const expBox = document.getElementById('quiz-explanation');
    expBox.innerHTML = `
        <div class="explanation-title">
            <i class="fas ${isCorrect ? 'fa-check-circle' : 'fa-info-circle'}"></i> 
            ${isCorrect ? 'Правильный ответ!' : 'Неверно'}
        </div>
        <p>${question.explanation}</p>
    `;
    expBox.style.display = 'block';

    // Enable next button
    document.getElementById('quiz-next-btn').disabled = false;
}

function nextQuestion() {
    const topic = state.quiz.activeTopic;
    const totalQuestions = QUIZ_DATA[topic].questions.length;

    state.quiz.currentQuestionIndex++;

    if (state.quiz.currentQuestionIndex < totalQuestions) {
        renderQuestion();
    } else {
        showQuizResults();
    }
}

function showQuizResults() {
    document.getElementById('quiz-active-area').style.display = 'none';
    
    const topic = state.quiz.activeTopic;
    const totalQuestions = QUIZ_DATA[topic].questions.length;
    const score = state.quiz.score;
    const pct = Math.round((score / totalQuestions) * 100);

    // Save results
    localStorage.setItem(`quiz_score_${topic}`, score);
    if (pct >= 80) {
        localStorage.setItem(`quiz_completed_${topic}`, 'true');
    }

    document.getElementById('quiz-progress-fill').style.width = `100%`;

    const scoreScreen = document.getElementById('quiz-score-screen');
    scoreScreen.style.display = 'block';

    document.getElementById('quiz-score-num').innerText = score;
    document.getElementById('quiz-score-total').innerText = `/ ${totalQuestions}`;

    let msg = "";
    if (pct === 100) msg = "Идеальный результат! Ты полностью готов!";
    else if (pct >= 80) msg = "Отличная подготовка! Тест сдан!";
    else if (pct >= 50) msg = "Неплохо, но стоит подучить теорию еще раз.";
    else msg = "Слабый результат. Рекомендуем прочитать шпаргалки и пройти тест заново.";

    document.getElementById('quiz-score-msg').innerText = msg;
    document.getElementById('quiz-score-details').innerText = `Процент правильных ответов: ${pct}%`;
}

