function calculateProgress(topic) {
    const completed = JSON.parse(localStorage.getItem(`quiz_completed_${topic}`) || 'false');
    if (completed) return 100;
    const score = localStorage.getItem(`quiz_score_${topic}`);
    if (score !== null) {
        const total = QUIZ_DATA[topic].questions.length;
        return Math.round((parseInt(score) / total) * 100);
    }
    return 0;
}

