// PHP-to-JS compilation logic
function transpilePHP(phpCode) {
    let js = phpCode;

    // Remove PHP tags
    js = js.replace(/<\?php/g, '');
    js = js.replace(/\?>/g, '');

    // Replace string concatenation dot "." with "+" only if not inside quotes and not surrounded by digits
    js = js.replace(/("([^"\\]|\\.)*")|('([^'\\]|\\.)*')|((?<!\d)\.(?!\d))/g, (match, doubleQuote, doubleInner, singleQuote, singleInner) => {
        if (doubleQuote || singleQuote) {
            return match; // Keep string literals unchanged
        }
        return ' + '; // Replace dots outside of string literals
    });

    // Replace PHP type hints in return: e.g. ": array", ": string", ": float", ": void"
    js = js.replace(/:\s*(array|string|int|float|bool|void|mixed|Vehicle|Car)/gi, '');

    // Replace PHP type hints in parameters: e.g. "array $numbers" -> "$numbers"
    js = js.replace(/(array|string|int|float|bool|mixed|Vehicle|Car)\s+\$/gi, '$');

    // Replace $this-> with this.
    js = js.replace(/\$this->/g, 'this.');

    // Replace parent::method() with super.method()
    js = js.replace(/parent::/g, 'super.');
    js = js.replace(/parent::__construct/g, 'super');

    // Replace public/protected/private property declarations: e.g., "private $brand;"
    js = js.replace(/(public|protected|private|var)\s+\$([a-zA-Z_]\w*)\s*;/gi, '');

    // Replace PHP array push shorthand: $result[] = $num; -> result.push(num);
    js = js.replace(/([a-zA-Z0-9_]+)\[\]\s*=\s*([^;]+)/g, '$1.push($2)');

    // Replace PHP foreach loop key-value and value-only BEFORE removing other dollar signs:
    // Key => Value: foreach($numbers as $key => $num) -> for (let [key, num] of Object.entries(numbers))
    js = js.replace(/foreach\s*\(\s*\$([a-zA-Z0-9_]+)\s+as\s+\$([a-zA-Z0-9_]+)\s*=>\s*\$([a-zA-Z0-9_]+)\s*\)/g, 'for (let [$2, $3] of Object.entries($1))');
    // Value only: foreach($numbers as $num) -> for (let num of Object.values(numbers))
    js = js.replace(/foreach\s*\(\s*\$([a-zA-Z0-9_]+)\s+as\s+\$([a-zA-Z0-9_]+)\s*\)/g, 'for (let $2 of Object.values($1))');

    // Handle class structure cleanups for JS (method declarations in JS classes don't need 'function' keyword)
    if (js.includes('class ')) {
        // Replace "public function ", "private function ", etc. with just empty space (method names)
        js = js.replace(/(public|protected|private)\s+function\s+/gi, ' ');
        // Replace standard function keyword inside classes
        js = js.replace(/class\s+(\w+)(?:\s+extends\s+(\w+))?\s*\{([\s\S]*?)\}/gi, (match, className, baseClass, body) => {
            let cleanBody = body.replace(/function\s+(\w+)/g, '$1');
            cleanBody = cleanBody.replace(/__construct/g, 'constructor');
            return `class ${className} ${baseClass ? 'extends ' + baseClass : ''} { ${cleanBody} }`;
        });
    }

    // Replace remaining variable occurrences $var with var
    js = js.replace(/\$([a-zA-Z_]\w*)/g, '$1');

    // Compile common PHP helper calls
    // count(arr) -> count(arr) helper
    // isset(x) -> isset helper
    js = js.replace(/isset\s*\(\s*([^)]+)\)/g, '(typeof $1 !== "undefined" && $1 !== null)');

    return js;
}

